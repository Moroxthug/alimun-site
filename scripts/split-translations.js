/**
 * Splits js/translations.js (the one file to edit) into per-language files
 * that pages load instead of the whole dictionary:
 *
 *   js/i18n/<lang>.js      text used by public pages (and anything not provably dashboard-only)
 *   js/i18n/<lang>.app.js  text used only by the dashboards (student, teacher, admin)
 *
 * A page loads English (the fallback) plus its own folder's language; dashboards also
 * load the .app files. js/i18n.js fetches another language on demand when the active
 * language differs from the folder (root pages that are translated in place).
 *
 * A key is dashboard-only when its name appears in a dashboard page or in the new dashboards'
 * scripts (js/app/) and nowhere in the other root pages or js/ files. Keys whose name appears nowhere (built dynamically,
 * e.g. `student_cat_${c}`) stay in the public files so they are always available.
 * Run by build.js; the output is committed like the locale folders.
 */
const fs = require('fs');
const path = require('path');

const APP_PAGES = ['student-dashboard.html', 'teacher-dashboard.html'];

module.exports = function splitTranslations(root, T) {
  const read = (f) => fs.readFileSync(path.join(root, f), 'utf8');
  const rootHtml = fs.readdirSync(root).filter((f) => f.endsWith('.html'));
  const jsFiles = fs.readdirSync(path.join(root, 'js'))
    .filter((f) => f.endsWith('.js') && f !== 'translations.js').map((f) => 'js/' + f);
  const appJs = fs.existsSync(path.join(root, 'js', 'app'))
    ? fs.readdirSync(path.join(root, 'js', 'app')).filter((f) => f.endsWith('.js')).map((f) => 'js/app/' + f) : [];
  const appSrc = [...APP_PAGES.filter((f) => rootHtml.includes(f)), ...appJs].map(read).join('\n');
  const otherSrc = [...rootHtml.filter((f) => !APP_PAGES.includes(f)), ...jsFiles].map(read).join('\n');

  const allKeys = new Set(Object.values(T).flatMap((d) => Object.keys(d)));
  const appKeys = new Set();
  for (const k of allKeys) {
    const re = new RegExp(`['"\`]${k}['"\`]|\\.${k}\\b|data-i18n(?:-[a-z]+)?="${k}"`);
    if (re.test(appSrc) && !re.test(otherSrc)) appKeys.add(k);
  }

  const outDir = path.join(root, 'js', 'i18n');
  fs.mkdirSync(outDir, { recursive: true });
  const header = '/* Generated by scripts/split-translations.js from js/translations.js. Do not edit. */\n';
  const body = (lang, dict, flag) => header
    + '(function () {\n'
    + '  var T = window.ALIMUN_TRANSLATIONS = window.ALIMUN_TRANSLATIONS || {};\n'
    + `  var d = T[${JSON.stringify(lang)}] = T[${JSON.stringify(lang)}] || {};\n`
    + `  var a = ${JSON.stringify(dict)};\n`
    + '  for (var k in a) d[k] = a[k];\n'
    + `  (window.${flag} = window.${flag} || {})[${JSON.stringify(lang)}] = true;\n`
    + '})();\n';

  const written = [];
  for (const [lang, dict] of Object.entries(T)) {
    const pub = {}, app = {};
    for (const [k, v] of Object.entries(dict)) (appKeys.has(k) ? app : pub)[k] = v;
    fs.writeFileSync(path.join(outDir, `${lang}.js`), body(lang, pub, 'ALIMUN_I18N_LANGS'));
    fs.writeFileSync(path.join(outDir, `${lang}.app.js`), body(lang, app, 'ALIMUN_I18N_APP_LANGS'));
    written.push(lang);
  }
  // Remove files of languages no longer in the dictionary
  for (const f of fs.readdirSync(outDir)) {
    const lang = f.replace(/\.app\.js$|\.js$/, '');
    if (!written.includes(lang)) fs.unlinkSync(path.join(outDir, f));
  }
  console.log(`Translations split: ${written.length} languages, ${allKeys.size - appKeys.size} public keys, ${appKeys.size} dashboard keys`);
  return { appKeys, languages: written };
};

module.exports.APP_PAGES = APP_PAGES;
